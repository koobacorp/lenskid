# Generates src/font.h: a small 1-bit pixel font (ASCII 32-126) for the dashcam date stamp.
from PIL import Image, ImageDraw, ImageFont
F = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf", 13)
CW, CH = 8, 13
rows = []
for c in range(32, 127):
    im = Image.new("L", (CW, CH), 0); d = ImageDraw.Draw(im)
    d.text((0, -2), chr(c), font=F, fill=255)
    bits = []
    for y in range(CH):
        v = 0
        for x in range(CW):
            if im.getpixel((x, y)) > 110: v |= 1 << x
        bits.append(v)
    rows.append(bits)
with open("src/font.h", "w") as f:
    f.write("// Generated by tools/gen_font.py: 8x13 bitmap font, ASCII 32-126, row 0 = top, bit x = column x.\n#pragma once\n")
    f.write("namespace lk { static const int kFontW = %d, kFontH = %d;\nstatic const unsigned char kFont[95][%d] = {\n" % (CW, CH, CH))
    for b in rows: f.write("  {" + ",".join(str(v) for v in b) + "},\n")
    f.write("};\n}\n")
